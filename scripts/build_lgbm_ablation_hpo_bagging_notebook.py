        "   - **`FoldLocalFeatureTransformer`:** Strictly fitted on fold training indices only. "
        "Implements numeric group means for income and commute, plus normalized frequency "
        "encodings "
        "with global training fallbacks.\n"
        "3. **Phase 1 (Feature Ablation):** Stratified 5-Fold evaluation comparing `raw`, "
        "`stateless`, and `fold_local` feature sets.\n"
        "4. **Phase 2 (Optuna HPO):** 15-trial Tree-structured Parzen Estimator (TPE, seed=42) "
        "optimizing 7 LightGBM tree structure and regularization hyperparameters.\n"
        "5. **Phase 3 (Repeated Bagging):** 5-fold x 3-repeat ensemble with multi-seed "
        "confirmation (`[42, 137, 2026]`) on the development subset. The selected candidate is "
