#!/usr/bin/env python3
"""Builds the LightGBM Ablation, HPO, and Bagging Kaggle Notebook.

This script generates an independent, leakage-safe notebook for Kaggle and local execution:
- Phase 1: Feature policy ablation (raw vs stateless vs fold_local) via 5-fold StratifiedKFold.
- Phase 2: Hyperparameter optimization via Optuna TPESampler over 7 parameters.
- Phase 3: Repeated Stratified K-Fold (5x3 confirmation) with seeds [42, 137, 2026].
- Export contract: submission.csv, oof_predictions.csv, feature_ablation.csv, hpo_trials.csv,
  fold_metrics.csv, and experiment_manifest.json.
"""

