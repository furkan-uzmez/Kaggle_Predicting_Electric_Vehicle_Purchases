    "    if CFG.USE_META_FEATURES and len(members) > 1:\n"
    "        frame['meta_consensus'] = stacked.mean(axis=1)\n"
    "        frame['meta_dispersion'] = stacked.std(axis=1)\n"
    "    return frame\n"
    "\n"
    "\n"
    "def run_level2(members):\n"
    "    \"\"\"Fit the meta-learner under an OUTER fold structure.\n"
    "\n"
    "    The meta-learner is never scored on the folds that produced its own inputs:\n"
    "    within each repeat it trains on the outer-training rows and predicts the\n"
    "    held-out rows of that same fold.\n"
    "    \"\"\"\n"
    "    oof_per_repeat = np.zeros((N_REPEATS, len(train_df)), dtype='float64')\n"
