def build_notebook() -> nbf.NotebookNode:
    """Assemble the diversity stack notebook."""
    nb = nbf.v4.new_notebook()
    nb.metadata["kernelspec"] = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    nb.metadata["language_info"] = {
        "name": "python",
        "version": "3.10.12",
        "mimetype": "text/x-python",
        "codemirror_mode": {"name": "ipython", "version": 3},
        "file_extension": ".py",
        "pygments_lexer": "ipython3",
    }

    sections = [
        (None, HEADER_MD),
        ("code", SETUP_CODE),
        (
            "md",
            "## 1. Configuration and declared gates\n\n"
            "Thresholds are fixed before anything runs. The reference is the adopted Arm C "
            "recipe, so a candidate must beat a strong model rather than the raw baseline.\n",
        ),
        ("code", CFG_CODE),
        ("md", "## 2. Data\n"),
        ("code", DATA_CODE),
        (
            "md",
            "## 3. Frozen split manifest\n\n"
            "Every Level 1 model, the meta-learner, and the combiner share one manifest, so "
            "all comparisons are paired per `(repeat, fold)`.\n",
        ),
        ("code", SPLIT_CODE),
        (
            "md",
            "## 4. Fold-local encoders\n\n"
            "Identical to the encoder gain study: fitted on outer training rows only, with "
            "inner cross-fitting for target encoding and no target argument on `transform`.\n",
        ),
        ("code", ENCODER_CODE),
        (
            "md",
            "## 5. Level 1 candidate grid\n\n"
            "Recipes vary what the model sees; model families vary how it learns. Measured "
            "evidence says the first axis decorrelates roughly three times as much, so the "
            "grid is recipe-heavy.\n",
        ),
        ("code", RECIPE_CODE),
        (
            "md",
            "## 6. Level 1 builders\n\n"
            "`build_recipe_matrices` materializes one recipe for one fold. Predictions are "
            "stored per repeat so fold scoring never mixes conventions.\n",
        ),
        ("code", BUILDER_CODE),
        (
            "md",
            "## 7. Train Level 1\n\n"
            "A failed candidate is recorded and skipped rather than aborting the run, so a "
            "single bad recipe cannot destroy the whole study.\n",
        ),
        ("code", LEVEL1_CODE),
        (
            "md",
            "## 8. Diversity screen\n\n"
            "The central question: are these models actually different? Greedy selection "
            "keeps the strongest model, then admits only candidates below the correlation "
            "ceiling. If fewer than two survive, the pool is too homogeneous and stacking "
            "cannot help.\n",
        ),
        ("code", DIVERSITY_CODE),
        (
            "md",
            "## 9. Level 2 and Level 3\n\n"
            "The meta-learner sees logit-transformed member predictions plus consensus and "
            "dispersion, and is scored under an outer fold structure. Level 3 is restricted "
            "to a simple weighted average; a flexible learner at this depth would fit "
            "validation noise twice.\n",
        ),
        ("code", LEVEL2_CODE),
        (
            "md",
            "## 10. Paired statistics\n\n"
            "Same protocol as every prior study: `ddof=1`, a real `t` quantile, the "
            "Nadeau-Bengio correction for fold overlap, Holm-Bonferroni across the candidate "
            "family, and the measured seed spread as a floor on what counts as real.\n",
        ),
        ("code", STATS_CODE),
        (
            "md",
            "## 11. Decision ledger\n\n"
            "Promotion requires a significant interval **and** the declared minimum lift. "
            "Retaining the reference is a complete result.\n",
        ),
        ("code", LEDGER_CODE),
        (
            "md",
            "## 12. Artifacts and submissions\n\n"
            "Correlation matrices, per-candidate metrics, meta-learner coefficients, OOF "
            "predictions, the ledger, a manifest, and one submission per candidate.\n",
        ),
        ("code", EXPORT_CODE),
    ]

    for kind, payload in sections:
        if kind == "code":
            nb.cells.append(nbf.v4.new_code_cell(payload))
        else:
            nb.cells.append(nbf.v4.new_markdown_cell(payload))
    return nb


def main() -> None:
    """Write the notebook to disk."""
    notebook = build_notebook()
    NOTEBOOK_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(NOTEBOOK_OUTPUT_PATH, "w", encoding="utf-8") as handle:
        nbf.write(notebook, handle)
    print(f"Wrote {NOTEBOOK_OUTPUT_PATH} with {len(notebook.cells)} cells")


if __name__ == "__main__":
    main()
