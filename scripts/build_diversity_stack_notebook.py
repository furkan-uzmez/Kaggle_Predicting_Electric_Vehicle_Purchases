STATS_CODE = (
    "def fold_scores(oof_per_repeat):\n"
    "    \"\"\"Score fold (r, f) with repeat r's predictions, never a repeat average.\"\"\"\n"
    "    return {\n"
    "        (s['repeat'], s['fold']): roc_auc_score(\n"
    "            y_true[s['valid']], oof_per_repeat[s['repeat'], s['valid']]\n"
    "        )\n"
    "        for s in FOLDS\n"
    "    }\n"
    "\n"
    "\n"
    "def paired_verdict(base, cand, min_lift, seed_spread):\n"
    "    \"\"\"Nadeau-Bengio corrected paired interval plus a gate-aware verdict.\"\"\"\n"
    "    keys = sorted(base)\n"
    "    diffs = np.array([cand[k] - base[k] for k in keys], dtype='float64')\n"
    "    n = diffs.size\n"
    "    mean_d = float(diffs.mean())\n"
    "    sd = float(diffs.std(ddof=1)) if n > 1 else 0.0\n"
    "    ratio = (1.0 / CFG.n_splits) / (1.0 - 1.0 / CFG.n_splits)\n"
    "    se = sd * np.sqrt(1.0 / n + ratio) if n > 1 else 0.0\n"
    "    t_crit = float(stats.t.ppf(1.0 - CFG.ALPHA / 2.0, df=n - 1)) if n > 1 else float('nan')\n"
    "    if se > 0:\n"
    "        low, high = mean_d - t_crit * se, mean_d + t_crit * se\n"
    "        p_raw = float(2.0 * (1.0 - stats.t.cdf(abs(mean_d) / se, df=n - 1)))\n"
    "    else:\n"
    "        low, high, p_raw = mean_d, mean_d, 1.0\n"
    "    if not (low > 0 or high < 0):\n"
    "        verdict = 'noise / inconclusive'\n"
    "    elif abs(mean_d) < seed_spread:\n"
    "        verdict = 'noise (within run-to-run variation)'\n"
    "    elif mean_d < 0:\n"
    "        verdict = 'worse than reference'\n"
    "    elif mean_d < min_lift:\n"
    "        verdict = 'detectable but below minimum lift'\n"
    "    else:\n"
    "        verdict = 'signal'\n"
    "    return {\n"
    "        'mean_delta': mean_d,\n"
    "        'ci_low': low,\n"
    "        'ci_high': high,\n"
    "        'p_raw': p_raw,\n"
    "        'verdict': verdict,\n"
    "    }\n"
    "\n"
    "\n"
    "def holm_adjust(p_values):\n"
    "    \"\"\"Holm-Bonferroni step-down adjustment preserving monotonicity.\"\"\"\n"
    "    order = np.argsort(p_values)\n"
    "    adjusted = np.empty(len(p_values), dtype='float64')\n"
    "    running = 0.0\n"
    "    for rank, idx in enumerate(order):\n"
    "        running = max(running, min(1.0, (len(p_values) - rank) * p_values[idx]))\n"
    "        adjusted[idx] = running\n"
    "    return adjusted\n"
    "\n"
    "\n"
    "def measure_seed_spread(seeds=(101, 202, 303)):\n"
    "    \"\"\"Run-to-run noise of the reference recipe with data held fixed.\"\"\"\n"
    "    spec = FOLDS[0]\n"
    "    X_tr, X_va, _ = build_recipe_matrices(\n"
    "        LEVEL1[REFERENCE_KEY]['recipe'], spec['train'], spec['valid']\n"
    "    )\n"
    "    scores = []\n"
    "    for seed in seeds:\n"
    "        model = lgb.LGBMClassifier(**CFG.LGBM_PARAMS, random_state=seed)\n"
    "        model.fit(X_tr, y_true[spec['train']])\n"
    "        scores.append(roc_auc_score(y_true[spec['valid']], model.predict_proba(X_va)[:, 1]))\n"
    "    return float(max(scores) - min(scores)), scores\n"
    "\n"
    "\n"
    "SEED_SPREAD, SEED_SCORES = measure_seed_spread()\n"
    "print(f'Seed spread: {SEED_SPREAD:.8f} from {[round(s, 7) for s in SEED_SCORES]}')\n"
    "\n"
    "REF_FOLDS = fold_scores(LEVEL1[REFERENCE_KEY]['oof_per_repeat'])\n"
    "ref_pooled = LEVEL1[REFERENCE_KEY]['pooled_roc_auc']\n"
    "print(f'Reference {REFERENCE_KEY}: pooled {ref_pooled:.7f}')\n"
)

