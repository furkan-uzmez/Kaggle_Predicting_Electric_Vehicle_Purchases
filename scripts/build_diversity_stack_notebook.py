#!/usr/bin/env python3
"""Builds the Kaggle EV Purchase Diversity Stack Notebook.

Tests whether a stack built from genuinely diverse Level 1 models can beat the
adopted Arm C single model (pooled OOF 0.9457947, public 0.94601).

The premise comes from measured evidence in the encoder gain study: changing the
feature recipe moved prediction correlation to 0.982, while changing the model
family only moved it to 0.996. Diversity therefore comes from what a model sees,
not from which library trains it. Level 1 is accordingly a grid of feature
recipes crossed with a small set of model families.

Pipeline:
- Level 1: N recipes x model families, each scored on one frozen 5x3 manifest.
- Diversity screen: greedy low-correlation subset selection on OOF predictions.
- Level 2: regularized meta-learner over logit-transformed OOF plus optional
  consensus and dispersion meta-features, scored under an outer fold structure.
- Level 3: simple combiner only (average, declared weights, or hill climbing).
- Verdicts: paired per-fold differences against Arm C with Nadeau-Bengio
  correction, Holm-Bonferroni adjustment, declared minimum lift, and seed spread.
"""

