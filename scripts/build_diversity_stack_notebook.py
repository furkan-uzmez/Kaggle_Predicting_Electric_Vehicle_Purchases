ENCODER_CODE = (
    "class ValueFrequencyEncoder:\n"
    "    \"\"\"Per-value counts learned from the outer training fold only.\"\"\"\n"
    "\n"
    "    def __init__(self, columns, unseen_count=0):\n"
    "        self.columns = list(columns)\n"
    "        self.unseen_count = unseen_count\n"
    "        self.mappings_ = {}\n"
    "\n"
    "    def fit(self, frame):\n"
    "        self.mappings_ = {\n"
    "            c: frame[c].value_counts(dropna=False).to_dict() for c in self.columns\n"
    "        }\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mappings_:\n"
    "            raise RuntimeError('ValueFrequencyEncoder not fitted')\n"
    "        out = {}\n"
    "        for c in self.columns:\n"
    "            mapped = frame[c].map(self.mappings_[c]).fillna(self.unseen_count)\n"
    "            out[f'{c}_freq'] = mapped.astype('int64').to_numpy()\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "class FloorFlagEncoder:\n"
    "    \"\"\"Binary indicators for training-fold mass points.\"\"\"\n"
    "\n"
    "    def __init__(self, columns, min_share):\n"
    "        self.columns = list(columns)\n"
    "        self.min_share = float(min_share)\n"
    "        self.mass_points_ = {}\n"
    "\n"
    "    def fit(self, frame):\n"
    "        threshold = max(1, int(np.ceil(self.min_share * len(frame))))\n"
    "        self.mass_points_ = {}\n"
    "        for c in self.columns:\n"
    "            counts = frame[c].value_counts(dropna=False)\n"
    "            self.mass_points_[c] = sorted(counts[counts >= threshold].index.tolist())\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mass_points_:\n"
    "            raise RuntimeError('FloorFlagEncoder not fitted')\n"
    "        out = {}\n"
    "        for c in self.columns:\n"
    "            values = frame[c].to_numpy()\n"
    "            for value in self.mass_points_[c]:\n"
    "                out[f'{c}_is_{value}'] = (values == value).astype('int64')\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "class SmoothedTargetEncoder:\n"
    "    \"\"\"Smoothed per-value buy rate with inner cross-fitting for training rows.\n"
    "\n"
    "    ``transform`` accepts no target argument, so validation labels cannot leak.\n"
    "    \"\"\"\n"
    "\n"
    "    def __init__(self, columns, m=20.0, n_inner_folds=5, random_state=42):\n"
    "        self.columns = list(columns)\n"
    "        self.m = float(m)\n"
    "        self.n_inner_folds = int(n_inner_folds)\n"
    "        self.random_state = int(random_state)\n"
    "        self.mappings_ = {}\n"
    "        self.global_mean_ = float('nan')\n"
    "\n"
    "    def _smoothed_map(self, values, y, prior):\n"
    "        grouped = pd.DataFrame({'v': values.to_numpy(), 'y': y}).groupby('v')['y']\n"
    "        counts, positives = grouped.count(), grouped.sum()\n"
    "        return ((positives + self.m * prior) / (counts + self.m)).to_dict()\n"
    "\n"
    "    def fit(self, frame, y):\n"
    "        y_arr = np.asarray(y, dtype='float64')\n"
    "        if y_arr.shape[0] != len(frame):\n"
    "            raise ValueError('y length must match frame length')\n"
    "        self.global_mean_ = float(y_arr.mean())\n"
    "        self.mappings_ = {\n"
    "            c: self._smoothed_map(frame[c], y_arr, self.global_mean_) for c in self.columns\n"
    "        }\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mappings_:\n"
    "            raise RuntimeError('SmoothedTargetEncoder not fitted')\n"
    "        out = {}\n"
    "        for c in self.columns:\n"
    "            mapped = frame[c].map(self.mappings_[c]).fillna(self.global_mean_)\n"
    "            out[f'{c}_te'] = mapped.astype('float64').to_numpy()\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "    def fit_transform(self, frame, y):\n"
    "        self.fit(frame, y)\n"
    "        y_arr = np.asarray(y, dtype='float64')\n"
    "        n_rows = len(frame)\n"
    "        out = {\n"
    "            f'{c}_te': np.full(n_rows, self.global_mean_, dtype='float64')\n"
    "            for c in self.columns\n"
    "        }\n"
    "        folds = min(self.n_inner_folds, n_rows)\n"
    "        if folds < 2:\n"
    "            return pd.DataFrame(out, index=frame.index)\n"
    "        positions = np.arange(n_rows)\n"
    "        labels = y_arr.astype('int64')\n"
    "        if np.bincount(labels, minlength=2).min() < folds:\n"
    "            rng = np.random.default_rng(self.random_state)\n"
    "            shuffled = rng.permutation(positions)\n"
    "            splits = [\n"
    "                (np.setdiff1d(positions, part), part)\n"
    "                for part in np.array_split(shuffled, folds)\n"
    "            ]\n"
    "        else:\n"
    "            inner = StratifiedKFold(\n"
    "                n_splits=folds, shuffle=True, random_state=self.random_state\n"
    "            )\n"
    "            splits = list(inner.split(positions.reshape(-1, 1), labels))\n"
    "        for in_tr, in_va in splits:\n"
    "            if len(in_tr) == 0 or len(in_va) == 0:\n"
    "                continue\n"
    "            prior = float(y_arr[in_tr].mean())\n"
    "            for c in self.columns:\n"
    "                mapping = self._smoothed_map(frame[c].iloc[in_tr], y_arr[in_tr], prior)\n"
    "                mapped = frame[c].iloc[in_va].map(mapping).fillna(prior)\n"
    "                out[f'{c}_te'][in_va] = mapped.astype('float64').to_numpy()\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "def extract_digits(frame, columns, k_low, k_high):\n"
    "    \"\"\"floor(|x| / 10**k) %% 10, rounded first so 0.7 does not become digit 6.\"\"\"\n"
    "    out = {}\n"
    "    for c in sorted(columns):\n"
    "        magnitude = np.abs(frame[c].to_numpy(dtype='float64'))\n"
    "        for k in range(k_low, k_high + 1):\n"
    "            digits = np.floor(np.round(magnitude / (10.0 ** k), 6)) % 10\n"
    "            out[f'{c}_digit_{k}'] = np.nan_to_num(digits, nan=-1.0).astype('int64')\n"
    "    return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "# Cheap assertions before any model is trained.\n"
    "_tr = pd.DataFrame({'v': [10, 10, 10, 20, 20, 30]})\n"
    "assert ValueFrequencyEncoder(['v']).fit(_tr).transform(\n"
    "    pd.DataFrame({'v': [10, 20, 999]})\n"
    ")['v_freq'].tolist() == [3, 2, 0], 'unseen value must fall back to 0'\n"
    "assert FloorFlagEncoder(['v'], 0.4).fit(_tr).mass_points_['v'] == [10]\n"
    "_loo = SmoothedTargetEncoder(['v'], m=0.0, n_inner_folds=4, random_state=0).fit_transform(\n"
    "    pd.DataFrame({'v': ['A'] * 4}), np.array([1, 0, 0, 0])\n"
    ")['v_te'].to_numpy()\n"
    "assert abs(_loo[0]) < 1e-12, 'positive row leaked its own label'\n"
    "assert extract_digits(pd.DataFrame({'x': [0.7]}), ['x'], -1, -1)['x_digit_-1'].iloc[0] == 7\n"
    "print('Encoder self-tests passed.')\n"
)

