    "def nadeau_bengio_ci(deltas, n_splits=CFG.n_splits, alpha=CFG.ALPHA):\n"
    "    \"\"\"Compute Nadeau-Bengio corrected confidence interval and two-tailed p-value.\"\"\"\n"
    "    if n_splits <= 1:\n"
    "        raise ValueError(f'n_splits must be > 1, got {n_splits}')\n"
    "    d = np.asarray(deltas, dtype=np.float64)\n"
    "    n = len(d)\n"
    "    mean_d = float(np.mean(d))\n"
    "    if n < 2:\n"
    "        return {'mean': mean_d, 'sd': 0.0, 'se_nb': 0.0, 'ci_low': mean_d, 'ci_high': mean_d, 'p_value': 1.0}\n"
