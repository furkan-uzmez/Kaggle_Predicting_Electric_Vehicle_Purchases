def build_notebook() -> nbf.NotebookNode:
    """Build the nbformat notebook object populated with complete study cells."""
    nb = nbf.v4.new_notebook()

    # Complete Study Cells:
    sections = [
        ("md", HEADER_MD),
        ("code", SETUP_CODE),
        ("md", MOTIVATION_MD),
        ("code", CFG_CODE),
        ("md", RESOLVER_MD),
        ("code", RESOLVER_CODE),
        ("md", DATA_MD),
        ("code", DATA_CODE),
        ("md", ENCODER_MD),
        ("code", ENCODER_CODE),
        ("md", PROTOCOL_MD),
        ("code", PROTOCOL_CODE),
        ("md", SELF_TEST_MD),
        ("code", SELF_TEST_CODE),
        ("md", FEATURES_MD),
        ("code", FEATURES_CODE),
        ("md", EVALUATION_MD),
        ("code", EVALUATION_CODE),
        ("md", PRECOMPUTE_MD),
        ("code", PRECOMPUTE_CODE),
        ("md", HPO_MD),
        ("code", HPO_CODE),
        ("md", CONFIRM_MD),
        ("code", CONFIRM_CODE),
        ("md", FINAL_MD),
        ("code", FINAL_CODE),
        ("md", GATE_MD),
        ("code", GATE_CODE),
        ("md", ARTIFACTS_MD),
        ("code", ARTIFACTS_CODE),
        ("md", INTERPRETATION_MD),
    ]

    for kind, payload in sections:
        if kind == "code":
            nb.cells.append(nbf.v4.new_code_cell(payload))
        else:
            nb.cells.append(nbf.v4.new_markdown_cell(payload))

    return nb


def main() -> None:
    """Write the notebook to disk."""
    notebook = build_notebook()
    NOTEBOOK_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(NOTEBOOK_OUTPUT_PATH, "w", encoding="utf-8") as handle:
        nbf.write(notebook, handle)
    print(f"Wrote {NOTEBOOK_OUTPUT_PATH} with {len(notebook.cells)} cells")


if __name__ == "__main__":
    main()
