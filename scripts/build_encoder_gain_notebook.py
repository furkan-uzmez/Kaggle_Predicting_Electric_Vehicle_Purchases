def build_notebook() -> nbf.NotebookNode:
    """Assemble the encoder gain notebook."""
    nb = nbf.v4.new_notebook()
    nb.metadata["kernelspec"] = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    nb.metadata["language_info"] = {
        "name": "python",
        "version": "3.10.12",
        "mimetype": "text/x-python",
        "codemirror_mode": {"name": "ipython", "version": 3},
        "file_extension": ".py",
        "pygments_lexer": "ipython3",
    }

    sections = [
        (None, HEADER_MD),
        ("code", SETUP_CODE),
        (
            "md",
            "## 1. Configuration and declared gates\n\n"
            "Every threshold that decides adoption is fixed here, before any arm runs. "
            "`SMOKE` defaults to `True`: run the cheap pass first, confirm the assertions hold, "
            "then set it to `False` for the full study.\n",
        ),
        ("code", CFG_CODE),
        (
            "md",
            "## 2. Data discovery and mass-point evidence\n\n"
            "Loads the competition files from Kaggle or a local checkout, then prints the "
            "mass-point structure that motivates value-level encoding.\n",
        ),
        ("code", DATA_CODE),
        (
            "md",
            "## 3. Frozen split manifest\n\n"
            "One `RepeatedStratifiedKFold` manifest is shared by every arm so all comparisons are "
            "paired. Assertions verify per-repeat coverage and the absence of train/validation "
            "overlap.\n",
        ),
        ("code", SPLIT_CODE),
        (
            "md",
            "## 4. Fold-local encoders\n\n"
            "Each encoder learns from outer training rows only. `SmoothedTargetEncoder` keeps two "
            "mappings: inner cross-fitted values for training rows, and full training-fold values "
            "for validation and test rows. Its `transform` takes no target argument, so validation "
            "labels cannot reach it.\n",
        ),
        ("code", ENCODER_CODE),
        (
            "md",
            "## 5. Encoder self-tests\n\n"
            "Cheap assertions that fail before any model is trained: unseen-value fallback, "
            "mass-point detection, leave-one-out target encoding, smoothing arithmetic, and "
            "floating-point-safe digit extraction.\n",
        ),
        ("code", ENCODER_SELFTEST_CODE),
        (
            "md",
            "## 6. Arm construction and training\n\n"
            "`build_arm_matrices` fits encoders on the fold's training rows and transforms the "
            "validation and test rows. `run_arm` stores predictions per repeat so fold scoring "
            "never mixes conventions.\n",
        ),
        ("code", BUILDER_CODE),
        (
            "md",
            "## 7. Paired statistics\n\n"
            "Fold differences use `ddof=1`, a real `t` quantile, and the Nadeau-Bengio correction "
            "`SE = s*sqrt(1/n + r)` for fold overlap. Holm-Bonferroni adjusts for the candidate "
            "family, and the measured seed spread bounds what counts as a real effect.\n",
        ),
        ("code", STATS_CODE),
        (
            "md",
            "## 8. Run the arms\n\n"
            "Arm A establishes the reference floor; the remaining arms add one encoding family at "
            "a time so each increment is attributable.\n",
        ),
        ("code", EXECUTE_CODE),
        (
            "md",
            "## 9. Seed spread, blend, and diversity\n\n"
            "The convention guard re-checks per-repeat scoring, the seed spread quantifies "
            "run-to-run noise, and the correlation matrix shows whether the arms are genuinely "
            "diverse or near-copies.\n",
        ),
        ("code", BLEND_CODE),
        (
            "md",
            "## 10. Decision ledger\n\n"
            "Each candidate receives a corrected interval, an adjusted p-value, and an explicit "
            "verdict. A candidate is promoted only when it clears the interval, the minimum lift, "
            "the seed spread, and the multiplicity correction. Retaining Arm A is a valid "
            "outcome.\n",
        ),
        ("code", LEDGER_CODE),
        (
            "md",
            "## 11. Artifacts and submissions\n\n"
            "Writes fold metrics, OOF predictions, correlations, the ledger, a run manifest, and "
            "one submission per arm. Public scores may be recorded afterwards as confirmation, "
            "never as a selection signal.\n",
        ),
        ("code", EXPORT_CODE),
    ]

    for kind, payload in sections:
        if kind == "code":
            nb.cells.append(nbf.v4.new_code_cell(payload))
        else:
            nb.cells.append(nbf.v4.new_markdown_cell(payload))
    return nb


def main() -> None:
    """Write the notebook to disk."""
    notebook = build_notebook()
    NOTEBOOK_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(NOTEBOOK_OUTPUT_PATH, "w", encoding="utf-8") as handle:
        nbf.write(notebook, handle)
    print(f"Wrote {NOTEBOOK_OUTPUT_PATH} with {len(notebook.cells)} cells")


if __name__ == "__main__":
    main()
