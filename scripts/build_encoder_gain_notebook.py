ENCODER_CODE = (
    "class ValueFrequencyEncoder:\n"
    "    \"\"\"Per-value occurrence counts learned from the outer training fold only.\"\"\"\n"
    "\n"
    "    def __init__(self, columns, unseen_count=0):\n"
    "        self.columns = list(columns)\n"
    "        self.unseen_count = unseen_count\n"
    "        self.mappings_ = {}\n"
    "\n"
    "    def fit(self, frame):\n"
    "        self.mappings_ = {\n"
    "            col: frame[col].value_counts(dropna=False).to_dict() for col in self.columns\n"
    "        }\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mappings_:\n"
    "            raise RuntimeError('ValueFrequencyEncoder must be fitted before transform')\n"
    "        out = {}\n"
    "        for col in self.columns:\n"
    "            mapped = frame[col].map(self.mappings_[col])\n"
    "            out[f'{col}_freq'] = mapped.fillna(self.unseen_count).astype('int64').to_numpy()\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "class FloorFlagEncoder:\n"
    "    \"\"\"Binary indicators for training-fold mass points above a share threshold.\"\"\"\n"
    "\n"
    "    def __init__(self, columns, min_share):\n"
    "        self.columns = list(columns)\n"
    "        self.min_share = float(min_share)\n"
    "        self.mass_points_ = {}\n"
    "\n"
    "    def fit(self, frame):\n"
    "        threshold = max(1, int(np.ceil(self.min_share * len(frame))))\n"
    "        self.mass_points_ = {}\n"
    "        for col in self.columns:\n"
    "            counts = frame[col].value_counts(dropna=False)\n"
    "            self.mass_points_[col] = sorted(counts[counts >= threshold].index.tolist())\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mass_points_:\n"
    "            raise RuntimeError('FloorFlagEncoder must be fitted before transform')\n"
    "        out = {}\n"
    "        for col in self.columns:\n"
    "            values = frame[col].to_numpy()\n"
    "            for value in self.mass_points_[col]:\n"
    "                out[f'{col}_is_{value}'] = (values == value).astype('int64')\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "class SmoothedTargetEncoder:\n"
    "    \"\"\"Smoothed per-value buy rate with inner cross-fitting for training rows.\n"
    "\n"
    "    ``transform`` accepts no target argument, so validation labels cannot leak in.\n"
    "    ``fit_transform`` encodes each training row from inner folds that exclude that\n"
    "    row's own label, which prevents a row from inflating its own encoded value.\n"
    "    \"\"\"\n"
    "\n"
    "    def __init__(self, columns, m=20.0, n_inner_folds=5, random_state=42):\n"
    "        self.columns = list(columns)\n"
    "        self.m = float(m)\n"
    "        self.n_inner_folds = int(n_inner_folds)\n"
    "        self.random_state = int(random_state)\n"
    "        self.mappings_ = {}\n"
    "        self.global_mean_ = float('nan')\n"
    "\n"
    "    def _smoothed_map(self, values, y, prior):\n"
    "        grouped = pd.DataFrame({'v': values.to_numpy(), 'y': y}).groupby('v')['y']\n"
    "        counts = grouped.count()\n"
    "        positives = grouped.sum()\n"
    "        return ((positives + self.m * prior) / (counts + self.m)).to_dict()\n"
    "\n"
    "    def fit(self, frame, y):\n"
    "        y_arr = np.asarray(y, dtype='float64')\n"
    "        if y_arr.shape[0] != len(frame):\n"
    "            raise ValueError('y length must match frame length')\n"
    "        self.global_mean_ = float(y_arr.mean())\n"
    "        self.mappings_ = {\n"
    "            col: self._smoothed_map(frame[col], y_arr, self.global_mean_)\n"
    "            for col in self.columns\n"
    "        }\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mappings_:\n"
    "            raise RuntimeError('SmoothedTargetEncoder must be fitted before transform')\n"
    "        out = {}\n"
    "        for col in self.columns:\n"
    "            mapped = frame[col].map(self.mappings_[col])\n"
    "            out[f'{col}_te'] = (\n"
    "                mapped.fillna(self.global_mean_).astype('float64').to_numpy()\n"
    "            )\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "    def fit_transform(self, frame, y):\n"
    "        self.fit(frame, y)\n"
    "        y_arr = np.asarray(y, dtype='float64')\n"
    "        n_rows = len(frame)\n"
    "        out = {\n"
    "            f'{col}_te': np.full(n_rows, self.global_mean_, dtype='float64')\n"
    "            for col in self.columns\n"
    "        }\n"
    "        folds = min(self.n_inner_folds, n_rows)\n"
    "        if folds < 2:\n"
    "            return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "        positions = np.arange(n_rows)\n"
    "        labels = y_arr.astype('int64')\n"
    "        counts = np.bincount(labels, minlength=2)\n"
    "        if counts.min() < folds:\n"
    "            # Stratification is impossible when a class has fewer members than\n"
    "            # folds. Fall back to a seeded plain split so the cross-fitting\n"
    "            # guarantee still holds instead of raising.\n"
    "            rng = np.random.default_rng(self.random_state)\n"
    "            shuffled = rng.permutation(positions)\n"
    "            splits = [\n"
    "                (np.setdiff1d(positions, part), part)\n"
    "                for part in np.array_split(shuffled, folds)\n"
    "            ]\n"
    "        else:\n"
    "            inner = StratifiedKFold(\n"
    "                n_splits=folds, shuffle=True, random_state=self.random_state\n"
    "            )\n"
    "            splits = list(inner.split(positions.reshape(-1, 1), labels))\n"
    "\n"
    "        for in_tr, in_va in splits:\n"
    "            if len(in_tr) == 0 or len(in_va) == 0:\n"
    "                continue\n"
    "            prior = float(y_arr[in_tr].mean())\n"
    "            for col in self.columns:\n"
    "                mapping = self._smoothed_map(frame[col].iloc[in_tr], y_arr[in_tr], prior)\n"
    "                mapped = frame[col].iloc[in_va].map(mapping).fillna(prior)\n"
    "                out[f'{col}_te'][in_va] = mapped.astype('float64').to_numpy()\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "class UnsupervisedCombinedFrequencyEncoder:\n"
    "    \"\"\"Value counts across train and unlabeled test predictors, using no labels.\n"
    "\n"
    "    Transductive: legitimate for a fixed competition test set, but a violation of\n"
    "    the production rule that test inputs never fit a transformer. Opt-in only.\n"
    "    \"\"\"\n"
    "\n"
    "    def __init__(self, columns, use_unlabeled=False, unseen_count=0):\n"
    "        self.columns = list(columns)\n"
    "        self.use_unlabeled = bool(use_unlabeled)\n"
    "        self.unseen_count = unseen_count\n"
    "        self.mappings_ = {}\n"
    "\n"
    "    def fit(self, frame, unlabeled_frame=None):\n"
    "        sources = [frame[self.columns]]\n"
    "        if self.use_unlabeled and unlabeled_frame is not None:\n"
    "            sources.append(unlabeled_frame[self.columns])\n"
    "        combined = pd.concat(sources, axis=0, ignore_index=True)\n"
    "        self.mappings_ = {\n"
    "            col: combined[col].value_counts(dropna=False).to_dict() for col in self.columns\n"
    "        }\n"
    "        return self\n"
    "\n"
    "    def transform(self, frame):\n"
    "        if not self.mappings_:\n"
    "            raise RuntimeError('UnsupervisedCombinedFrequencyEncoder must be fitted first')\n"
    "        out = {}\n"
    "        for col in self.columns:\n"
    "            mapped = frame[col].map(self.mappings_[col])\n"
    "            out[f'{col}_allfreq'] = (\n"
    "                mapped.fillna(self.unseen_count).astype('int64').to_numpy()\n"
    "            )\n"
    "        return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "def extract_digits(frame, columns, k_low, k_high):\n"
    "    \"\"\"Emit floor(|x| / 10**k) %% 10 for k in [k_low, k_high].\n"
    "\n"
    "    Rounding before the floor keeps binary representation error from turning 0.7\n"
    "    into digit 6. Stateless, so it is safe to apply outside the fold loop.\n"
    "    \"\"\"\n"
    "    out = {}\n"
    "    for col in sorted(columns):\n"
    "        magnitude = np.abs(frame[col].to_numpy(dtype='float64'))\n"
    "        for k in range(k_low, k_high + 1):\n"
    "            scaled = magnitude / (10.0 ** k)\n"
    "            digits = np.floor(np.round(scaled, 6)) % 10\n"
    "            out[f'{col}_digit_{k}'] = np.nan_to_num(digits, nan=-1.0).astype('int64')\n"
    "    return pd.DataFrame(out, index=frame.index)\n"
    "\n"
    "\n"
    "print('Fold-local encoders defined.')\n"
)

