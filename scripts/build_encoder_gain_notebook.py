STATS_CODE = (
    "def fold_scores_from_per_repeat(oof_per_repeat):\n"
    "    \"\"\"Score fold (r, f) using repeat r's predictions, never a repeat average.\n"
    "\n"
    "    Mixing conventions here is exactly the defect that produced a spurious\n"
    "    positive lift in an earlier study, so the convention is asserted at runtime.\n"
    "    \"\"\"\n"
    "    scores = {}\n"
    "    for spec in FOLDS:\n"
    "        repeat, fold, va = spec['repeat'], spec['fold'], spec['valid']\n"
    "        scores[(repeat, fold)] = roc_auc_score(y_true[va], oof_per_repeat[repeat, va])\n"
    "    return scores\n"
    "\n"
    "\n"
    "def paired_verdict(base_scores, cand_scores, min_lift, seed_spread):\n"
    "    \"\"\"Nadeau-Bengio corrected paired interval plus a gate-aware verdict.\"\"\"\n"
    "    keys = sorted(base_scores)\n"
    "    diffs = np.array([cand_scores[k] - base_scores[k] for k in keys], dtype='float64')\n"
    "    n = diffs.size\n"
    "    mean_d = float(diffs.mean())\n"
    "    sd = float(diffs.std(ddof=1)) if n > 1 else 0.0\n"
    "    ratio = (1.0 / CFG.n_splits) / (1.0 - 1.0 / CFG.n_splits)\n"
    "    se_nb = sd * np.sqrt(1.0 / n + ratio) if n > 1 else 0.0\n"
    "    t_crit = float(stats.t.ppf(1.0 - CFG.ALPHA / 2.0, df=n - 1)) if n > 1 else float('nan')\n"
    "\n"
    "    if se_nb > 0:\n"
    "        low, high = mean_d - t_crit * se_nb, mean_d + t_crit * se_nb\n"
    "        p_raw = float(2.0 * (1.0 - stats.t.cdf(abs(mean_d) / se_nb, df=n - 1)))\n"
    "    else:\n"
    "        low, high, p_raw = mean_d, mean_d, 1.0\n"
    "\n"
    "    excludes_zero = low > 0 or high < 0\n"
    "    if not excludes_zero:\n"
    "        verdict = 'noise / inconclusive'\n"
    "    elif abs(mean_d) < seed_spread:\n"
    "        verdict = 'noise (within run-to-run variation)'\n"
    "    elif mean_d < 0:\n"
    "        verdict = 'worse than baseline'\n"
    "    elif mean_d < min_lift:\n"
    "        verdict = 'detectable but below minimum lift'\n"
    "    else:\n"
    "        verdict = 'signal'\n"
    "\n"
    "    return {\n"
    "        'mean_delta': mean_d,\n"
    "        'sd': sd,\n"
    "        'se_nb': se_nb,\n"
    "        't_crit': t_crit,\n"
    "        'ci_low': low,\n"
    "        'ci_high': high,\n"
    "        'p_raw': p_raw,\n"
    "        'n_folds': n,\n"
    "        'verdict': verdict,\n"
    "    }\n"
    "\n"
    "\n"
    "def holm_adjust(p_values):\n"
    "    \"\"\"Holm-Bonferroni step-down adjustment preserving monotonicity.\"\"\"\n"
    "    order = np.argsort(p_values)\n"
    "    adjusted = np.empty(len(p_values), dtype='float64')\n"
    "    running = 0.0\n"
    "    for rank, idx in enumerate(order):\n"
    "        scaled = (len(p_values) - rank) * p_values[idx]\n"
    "        running = max(running, min(1.0, scaled))\n"
    "        adjusted[idx] = running\n"
    "    return adjusted\n"
    "\n"
    "\n"
    "def measure_seed_spread(arm='A', seeds=(101, 202, 303)):\n"
    "    \"\"\"Pooled-AUC spread of one configuration across seeds, data held fixed.\n"
    "\n"
    "    This is the second noise source: the paired interval measures split noise,\n"
    "    this measures run-to-run noise. Neither substitutes for the other.\n"
    "    \"\"\"\n"
    "    spec = FOLDS[0]\n"
    "    X_tr, X_va, _ = build_arm_matrices(arm, spec['train'], spec['valid'])\n"
    "    y_tr, y_va = y_true[spec['train']], y_true[spec['valid']]\n"
    "    scores = []\n"
    "    for seed in seeds:\n"
    "        model = lgb.LGBMClassifier(**CFG.LGBM_PARAMS, random_state=seed)\n"
    "        model.fit(X_tr, y_tr)\n"
    "        scores.append(roc_auc_score(y_va, model.predict_proba(X_va)[:, 1]))\n"
    "    return float(max(scores) - min(scores)), scores\n"
    "\n"
    "\n"
    "print('Statistics helpers defined.')\n"
)

