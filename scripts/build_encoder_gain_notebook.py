#!/usr/bin/env python3
"""Builds the Kaggle EV Purchase Value-Level Encoding Gain Notebook.

Generates a fully self-contained, leakage-safe Jupyter notebook that measures the
four value-level encoding techniques documented by public S6E9 solutions against
our frozen LightGBM trial35 baseline:

- Arm B: fold-local value frequency encoding plus mass-point (floor) flags.
- Arm C: Arm B plus fold-local smoothed target encoding with inner cross-fitting.
- Arm D: Arm C plus unsupervised train+test combined frequency (opt-in, transductive).
- Arm E: XGBoost on every-digit extraction plus frequencies.
- Arm F: weighted blend of the best LightGBM arm and Arm E, chosen on OOF only.

Every arm reuses one frozen 5x3 RepeatedStratifiedKFold manifest, and every
stateful encoder is fitted strictly inside each outer training fold. Verdicts come
from paired per-fold differences with a Nadeau-Bengio correction, Holm-Bonferroni
adjustment, a pre-declared minimum lift, and the measured seed spread.
"""

